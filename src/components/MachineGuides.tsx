import { polygonPath } from '../lib/generated-registration';
import { machineGuide, type GuideRect, type Machine } from '../lib/machine-guides';

type Props = {
  machine: Machine;
  paper: 'letter' | 'a4';
  area: GuideRect;
  captured?: boolean;
  optical?: boolean;
};
/** Screen annotations around the same black mark geometry used by generated PDFs. */
export function MachineGuideShapes({
  machine,
  paper,
  area,
  captured = false,
  optical = true,
}: Props) {
  const guide = machineGuide(machine, paper),
    b = guide.bounds;
  const generated = guide.optical && optical && !captured;
  const boundary = generated ? b : area;
  const { width: w, height: h } = guide.page;
  return (
    <g pointerEvents="none" aria-label="Sheet space and keep-out guides">
      <path
        d={`M0 0H${w}V${h}H0Z M${boundary.x} ${boundary.y}v${boundary.height}h${boundary.width}v${-boundary.height}Z`}
        fill="#64748b"
        fillOpacity="0.15"
        fillRule="evenodd"
      />
      {generated && (
        <>
          <text x={w / 2} y={7} textAnchor="middle" fontSize={3} fill="#79633f">
            Generated registration marks · print with the artwork
          </text>
          <rect {...b} fill="none" stroke="#c17d17" strokeWidth="0.35" strokeDasharray="2 1" />
          <g>
            {guide.corners.map((corner, i) => (
              <rect
                key={i}
                {...corner}
                fill="#d79a31"
                fillOpacity="0.23"
                stroke="#b77a1c"
                strokeWidth="0.2"
                strokeDasharray="1 1"
              />
            ))}
            {guide.marks.map((points, i) => (
              <path key={i} d={polygonPath(points)} fill="black" />
            ))}
          </g>
        </>
      )}
      <rect {...area} fill="none" stroke="#3877ae" strokeWidth="0.4" strokeDasharray="2 1" />
    </g>
  );
}
export function MachineGuideLegend({
  machine,
  paper,
  area,
  captured = false,
  optical = true,
  conflicts = 0,
}: Props & { conflicts?: number }) {
  const guide = machineGuide(machine, paper);
  return (
    <div className="machine-guide-legend" role="status">
      <strong>
        {guide.name} · {paper === 'a4' ? 'A4' : 'US Letter'}
      </strong>
      <span>
        Blue: layout area {area.width.toFixed(1)} × {area.height.toFixed(1)} mm · gray: outside the
        planning area.
      </span>
      {guide.optical && optical ? (
        captured ? (
          <span>
            Registration marks are included in the print PDF from your matching captured template.
            Keep the printed marks clear.
          </span>
        ) : (
          <>
            <span>
              Maximum extents: {guide.bounds.width.toFixed(1)} mm wide /{' '}
              {guide.bounds.height.toFixed(1)} mm tall. Corners reduce usable space.
            </span>
            <span>
              Black registration marks are generated by CriProx and included in its marked print
              PDF, 12.7 mm (0.5 in) inside the paper edge. Amber areas reserve sensor clearance.
              Check alignment when changing paper, material, or settings.
            </span>
            {!!conflicts && (
              <strong className="guide-conflict">
                {conflicts} item{conflicts === 1 ? '' : 's'} cross the planning limits or reserved
                corners. Check the layout before printing.
              </strong>
            )}
          </>
        )
      ) : (
        <span>
          Manual / Basic Cut layout: no optical registration marks. Check your printer’s margins.
        </span>
      )}
    </div>
  );
}
